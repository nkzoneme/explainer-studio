#!/usr/bin/env python3
"""channels/<slug>/style.json sound.kit_roles -> kit/sfx_v2/palette.js (window.KIT_PALETTES[slug] = role -> [sfx_v2 names]).
Usage: python3 kit/tools/build_palette.py   (run after editing a channel's sound.kit_roles)"""
import json,glob,os
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
idx=json.load(open(R+"/sfx_v2/index.json")); out={}
for p in sorted(glob.glob(R+"/../channels/*/style.json")):
    s=json.load(open(p)).get("sound",{}); k=s.get("kit_roles")
    if not k: continue
    bad=[n for v in k.values() for n in v if n not in idx]
    assert not bad,(p,bad)
    out[os.path.basename(os.path.dirname(p))]={r:v for r,v in k.items() if v}
open(R+"/sfx_v2/palette.js","w").write("/* generated by kit/tools/build_palette.py from channels/<slug>/style.json sound.kit_roles */\nwindow.KIT_PALETTES = "+json.dumps(out)+";\n")
print({k:len(v) for k,v in out.items()})
