#!/usr/bin/env python3
"""Per-frame speech level for mouth sync. Usage:
  python3 speech_levels.py <voiceover.mp3> <out levels.js> [fps=30]
Writes `window.KIT_LEVELS = [...]` : one 0..1 value per video frame (RMS of the dry voice in that frame,
normalised to the 95th percentile, light 3-frame smoothing). Use the DRY voice, never a mix with SFX/music."""
import sys, subprocess, json
import numpy as np
src, out = sys.argv[1], sys.argv[2]; fps = int(sys.argv[3]) if len(sys.argv) > 3 else 30
SR = 24000
x = np.frombuffer(subprocess.run(['ffmpeg','-v','error','-i',src,'-ac','1','-ar',str(SR),'-f','f32le','-'],capture_output=True,check=True).stdout, dtype=np.float32).astype(np.float64)
h = SR // fps; n = len(x) // h
rms = np.sqrt(np.mean(x[:n*h].reshape(n, h)**2, axis=1))
ref = np.percentile(rms[rms > rms.max()*0.02], 95)
lv = np.clip(rms / ref, 0, 1) ** 0.6           # compress: quiet vowels still open the mouth
lv = np.convolve(lv, [0.2, 0.6, 0.2], mode='same')
open(out, 'w').write('/* generated by kit/tools/speech_levels.py from %s */\nwindow.KIT_LEVELS = %s;\n' % (src.split('/')[-1], json.dumps([round(float(v), 2) for v in lv])))
print('frames', n, 'mean', round(float(lv.mean()), 2))
